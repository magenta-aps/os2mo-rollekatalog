@pytest.mark.integration_test
@pytest.mark.envvar({"LISTEN_TO_CHANGES_IN_MO": "False"})
async def test_current_email_preferred_over_future(
    test_client: AsyncClient,
    graphql_client: GraphQLClient,
    trigger_event: Callable[[str, uuid.UUID], Awaitable[None]],
    root_uuid: uuid.UUID,
    email_employee: uuid.UUID,
    create_it_system: Callable[..., Awaitable[uuid.UUID]],
    create_ituser: Callable[..., Awaitable[uuid.UUID]],
    create_address: Callable[..., Awaitable[uuid.UUID]],
) -> None:
    """With one address valid now and one only valid in the future, the
    current one is used."""
    # Arrange: a person with one AD account and two linked emails, one of
    # which only becomes valid in a year.
    employee = (
        await graphql_client._testing__create_employee(
            input=EmployeeCreateInput(given_name="Andersine", surname="And")
        )
    ).uuid
    AD = await create_it_system("Active Directory")
    FK = await create_it_system("FK ORG")
    object_guid, external_id = uuid.uuid4(), uuid.uuid4()
    ituser = await create_ituser(
        itsystem=AD,
        external_id=str(object_guid),
        person=employee,
        user_key="AsA",
        engagements=[],
    )
    await create_ituser(
        itsystem=FK,
        external_id=str(external_id),
        person=employee,
        user_key=str(object_guid),
        engagements=[],
    )
    await create_address(
        person=employee,
        value="future@example.org",
        address_type=email_employee,
        ituser=ituser,
        from_=datetime.now() + timedelta(days=365),
    )
    await create_address(
        person=employee,
        value="current@example.org",
        address_type=email_employee,
        ituser=ituser,
    )

    # Act.
    await trigger_event("person", employee)

    # Assert.
    user = one((await test_client.get(f"/cache/person/{employee}")).json())
    assert user["email"] == "current@example.org"


@pytest.mark.integration_test
@pytest.mark.envvar({"LISTEN_TO_CHANGES_IN_MO": "False"})
async def test_newest_email_wins_among_multiple_current(
    test_client: AsyncClient,
    graphql_client: GraphQLClient,
    trigger_event: Callable[[str, uuid.UUID], Awaitable[None]],
    root_uuid: uuid.UUID,
    email_employee: uuid.UUID,
    create_it_system: Callable[..., Awaitable[uuid.UUID]],
    create_ituser: Callable[..., Awaitable[uuid.UUID]],
    create_address: Callable[..., Awaitable[uuid.UUID]],
) -> None:
    """With several currently valid addresses, the newest one is used — the
    one whose validity starts latest — not the most recently edited."""
    # Arrange: two linked emails, both valid now. The seed-dated one is edited
    # recently (its current version then starts after the 2020 one). Newest
    # created first so query order cannot accidentally satisfy the assert.
    employee = (
        await graphql_client._testing__create_employee(
            input=EmployeeCreateInput(given_name="Georg", surname="Gearløs")
        )
    ).uuid
    AD = await create_it_system("Active Directory")
    FK = await create_it_system("FK ORG")
    object_guid, external_id = uuid.uuid4(), uuid.uuid4()
    ituser = await create_ituser(
        itsystem=AD,
        external_id=str(object_guid),
        person=employee,
        user_key="GG",
        engagements=[],
    )
    await create_ituser(
        itsystem=FK,
        external_id=str(external_id),
        person=employee,
        user_key=str(object_guid),
        engagements=[],
    )
    await create_address(
        person=employee,
        value="newest@example.org",
        address_type=email_employee,
        ituser=ituser,
        from_=datetime(2020, 1, 1),
    )
    oldest = await create_address(
        person=employee,
        value="oldest@example.org",
        address_type=email_employee,
        ituser=ituser,
    )
    await graphql_client._testing__update_address(
        input=AddressUpdateInput(
            uuid=oldest,
            person=employee,
            value="oldest-edited@example.org",
            address_type=email_employee,
            ituser=ituser,
            validity=RAValidityInput(from_=datetime(2026, 1, 1)),
        )
    )

    # Act.
    await trigger_event("person", employee)

    # Assert.
    user = one((await test_client.get(f"/cache/person/{employee}")).json())
    assert user["email"] == "newest@example.org"
