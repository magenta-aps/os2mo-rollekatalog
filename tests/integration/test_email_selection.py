@pytest.mark.integration_test
@pytest.mark.envvar({"LISTEN_TO_CHANGES_IN_MO": "False"})
async def test_email_linked_to_ituser_goes_to_that_account(
    test_client: AsyncClient,
    graphql_client: GraphQLClient,
    trigger_event: Callable[[str, uuid.UUID], Awaitable[None]],
    root_uuid: uuid.UUID,
    email_employee: uuid.UUID,
    create_it_system: Callable[..., Awaitable[uuid.UUID]],
    create_ituser: Callable[..., Awaitable[uuid.UUID]],
    create_address: Callable[..., Awaitable[uuid.UUID]],
) -> None:
    """An email linked to an ituser is only used for that account."""
    # Arrange: a person with two AD accounts, and an email linked to one.
    employee = (
        await graphql_client._testing__create_employee(
            input=EmployeeCreateInput(given_name="Anders", surname="And")
        )
    ).uuid
    AD = await create_it_system("Active Directory")
    FK = await create_it_system("FK ORG")
    linked_guid, linked_external = uuid.uuid4(), uuid.uuid4()
    other_guid, other_external = uuid.uuid4(), uuid.uuid4()
    linked_ituser = await create_ituser(
        itsystem=AD,
        external_id=str(linked_guid),
        person=employee,
        user_key="LINKED",
        engagements=[],
    )
    await create_ituser(
        itsystem=FK,
        external_id=str(linked_external),
        person=employee,
        user_key=str(linked_guid),
        engagements=[],
    )
    await create_ituser(
        itsystem=AD,
        external_id=str(other_guid),
        person=employee,
        user_key="OTHER",
        engagements=[],
    )
    await create_ituser(
        itsystem=FK,
        external_id=str(other_external),
        person=employee,
        user_key=str(other_guid),
        engagements=[],
    )
    await create_address(
        person=employee,
        value="linked@example.org",
        address_type=email_employee,
        ituser=linked_ituser,
    )

    # Act.
    await trigger_event("person", employee)

    # Assert: only the linked account gets the email.
    users = (await test_client.get(f"/cache/person/{employee}")).json()
    email_by_user = {user["userId"]: user["email"] for user in users}
    assert email_by_user == {"LINKED": "linked@example.org", "OTHER": None}


